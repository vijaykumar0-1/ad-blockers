// Builds dist/safari: the same extension, adjusted for Safari.
//
//   - the service worker is bundled into one classic script (no ES module imports)
//   - the manifest drops Chrome-only keys and requires Safari 26, the first version
//     whose blocking rules support initiatorDomains (used by many filter-list rules)
//
// safari/build.sh then wraps dist/safari in a Mac app with Apple's converter.
// Usage: node tools/build-safari.mjs   (no dependencies, no network access)

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "dist", "safari");

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "src"), { recursive: true });

for (const dir of ["rules", "icons"]) cpSync(join(root, dir), join(out, dir), { recursive: true });
for (const file of ["LICENSE", "src/popup.html", "src/popup.css", "src/popup.js", "src/cosmetic.js"]) {
  cpSync(join(root, file), join(out, file));
}

// Inline the module imports of background.js, in dependency order.
const stripExports = (code) => code.replace(/^export\s+(?=(async\s+)?function|const|let|class)/gm, "");
const modules = ["src/cosmetic-lookup.js", "src/popup-match.js"].map(
  (f) => `// ---- ${f} ----\n${stripExports(readFileSync(join(root, f), "utf8"))}`
);
const background = readFileSync(join(root, "src/background.js"), "utf8").replace(/^import .*;\n/gm, "");
writeFileSync(
  join(out, "src", "background.js"),
  `// Generated by tools/build-safari.mjs from src/. Do not edit.\n"use strict";\n${modules.join("\n")}\n// ---- src/background.js ----\n${background}`
);

const manifest = JSON.parse(readFileSync(join(root, "manifest.json"), "utf8"));
delete manifest.minimum_chrome_version;
// Content-script keys Safari doesn't support (it ignores them, but the converter warns).
for (const cs of manifest.content_scripts || []) {
  delete cs.match_origin_as_fallback;
  delete cs.match_about_blank;
}
// Safari's app icon comes from the largest size.
manifest.icons = { ...manifest.icons, 256: "icons/icon-256.png", 512: "icons/icon-512.png" };
manifest.background = { service_worker: "src/background.js" };
manifest.browser_specific_settings = { safari: { strict_min_version: "26.0" } };
writeFileSync(join(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

console.log(`dist/safari ready (LocalBlock ${manifest.version})`);
